let done = 0;
let skip = 0;
for (const [slug, html] of Object.entries(ADD)) {
  const file = join(ROOT, "articles", `${slug}.html`);
  if (!existsSync(file)) {
    console.log(`없음: ${slug}.html`);
    skip++;
    continue;
  }
  const src = readFileSync(file, "utf8");
  if (src.includes(MARK)) {
    skip++;
    continue;
  }
  if (!src.includes(ANCHOR)) {
    console.log(`앵커 없음(수동 처리 필요): ${slug}.html`);
    skip++;
    continue;
  }
  writeFileSync(file, src.replace(ANCHOR, `${html}\n    </div>\n  </main>`), "utf8");
  done++;
}
console.log(`지식 글 보강 — 적용 ${done}건 · 건너뜀 ${skip}건`);
